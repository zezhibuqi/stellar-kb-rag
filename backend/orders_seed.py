def build_orders() -> list[dict]:
    """按硬编码数据构造订单列表（确定性）。"""
    orders = []
    for date_str, seq, customer_idx, product, qty, payment, completed in _ORDER_DATA:
        customer, contact = CUSTOMERS[customer_idx]
        created_at = f"{date_str} {8 + (seq % 10):02d}:{(seq * 7) % 60:02d}:00"
        completed_at = None
        if completed:
            created_dt = datetime.strptime(created_at, "%Y-%m-%d %H:%M:%S")
            completed_at = (created_dt + timedelta(days=5)).strftime(
                "%Y-%m-%d 16:00:00"
            )
        orders.append(
            {
                "order_no": f"DD{date_str.replace('-', '')}{seq:03d}",
                "customer_name": customer,
                "contact": contact,
                "product_type": product,
                "quantity": qty,
                "created_at": created_at,
                "completed_at": completed_at,
                "payment_method": payment,
                "total_amount": float(PRODUCT_PRICES[product] * qty),
            }
        )
    return orders


def seed_orders() -> int:
    """表为空时写入种子订单；幂等。"""
    conn = get_connection()
    count = conn.execute("SELECT COUNT(*) FROM orders").fetchone()[0]
    if count:
        return count
    rows = build_orders()
    conn.executemany(
        "INSERT INTO orders (order_no, customer_name, contact, product_type, "
        "quantity, created_at, completed_at, payment_method, total_amount) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
        [
            (
                order["order_no"],
                order["customer_name"],
                order["contact"],
                order["product_type"],
                order["quantity"],
                order["created_at"],
                order["completed_at"],
                order["payment_method"],
                order["total_amount"],
            )
            for order in rows
        ],
    )
    conn.commit()
    return len(rows)
